let currentLang = localStorage.getItem("jarnToLang") || "lo";

function t(obj){
  return typeof obj === "string" ? obj : (obj[currentLang] || obj.lo);
}

function applyLanguage(){
  document.documentElement.lang = currentLang;
  document.documentElement.dataset.lang = currentLang;
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key=el.dataset.i18n;
    if(I18N[currentLang][key]!==undefined) el.innerHTML=I18N[currentLang][key];
  });
  document.querySelectorAll(".lang-btn").forEach(b=>b.classList.toggle("active",b.dataset.lang===currentLang));
  renderProjects(document.querySelector(".filter.active")?.dataset.filter || "all");
  renderGallery();
  renderVideos();
  localStorage.setItem("jarnToLang",currentLang);
}

function renderProjects(filter="all"){
  const grid=document.getElementById("projectGrid");
  grid.innerHTML=PROJECTS.filter(p=>filter==="all"||p.category===filter).map(p=>`
    <article class="project-card reveal visible" data-id="${p.id}">
      <img class="project-image" src="${p.image}" alt="${t(p.title)}" onerror="this.src='images/placeholder.svg'">
      <div class="project-info">
        <div class="category">${p.category}</div>
        <h3>${t(p.title)}</h3>
        <p>${t(p.desc)}</p>
      </div>
    </article>`).join("");
  grid.querySelectorAll(".project-card").forEach(card=>{
    card.addEventListener("click",()=>openProject(Number(card.dataset.id)));
  });
}

function renderGallery(){
  const grid=document.getElementById("galleryGrid");
  grid.innerHTML=GALLERY.map((g,i)=>`
    <div class="gallery-item reveal visible" data-index="${i}">
      <img src="${g.image}" alt="${t(g.title)}" onerror="this.src='images/placeholder.svg'">
    </div>`).join("");
  grid.querySelectorAll(".gallery-item").forEach(item=>{
    item.addEventListener("click",()=>openGallery(Number(item.dataset.index)));
  });
}

function renderVideos(){
  const grid=document.getElementById("videoGrid");
  grid.innerHTML=VIDEOS.map(v=>{
    const media=v.src
      ? `<video controls preload="metadata" poster="${v.poster}"><source src="${v.src}" type="video/mp4"></video>`
      : `<div class="video-placeholder">🎬<br>${currentLang==="lo"?"ໃສ່ໄຟລ໌ MP4 ຂອງຂ້ອຍທີ່ js/projects.js":"Add your MP4 file in js/projects.js"}</div>`;
    return `<article class="video-card reveal visible">${media}<div class="video-info"><h3>${t(v.title)}</h3><p>${t(v.desc)}</p></div></article>`;
  }).join("");
}

function openProject(id){
  const p=PROJECTS.find(x=>x.id===id); if(!p)return;
  document.getElementById("modalImage").src=p.image;
  document.getElementById("modalImage").onerror=()=>document.getElementById("modalImage").src="images/placeholder.svg";
  document.getElementById("modalCategory").textContent=p.category;
  document.getElementById("modalTitle").textContent=t(p.title);
  document.getElementById("modalDescription").textContent=t(p.desc);
  document.getElementById("modalTags").innerHTML=p.tags.map(x=>`<span class="tag">${x}</span>`).join("");
  openModal();
}
function openGallery(i){
  const g=GALLERY[i];
  document.getElementById("modalImage").src=g.image;
  document.getElementById("modalImage").onerror=()=>document.getElementById("modalImage").src="images/placeholder.svg";
  document.getElementById("modalCategory").textContent=g.category;
  document.getElementById("modalTitle").textContent=t(g.title);
  document.getElementById("modalDescription").textContent="";
  document.getElementById("modalTags").innerHTML="";
  openModal();
}
function openModal(){document.getElementById("modal").classList.add("open");document.getElementById("modal").setAttribute("aria-hidden","false")}
function closeModal(){document.getElementById("modal").classList.remove("open");document.getElementById("modal").setAttribute("aria-hidden","true")}

document.addEventListener("DOMContentLoaded",()=>{
  document.getElementById("year").textContent=new Date().getFullYear();

  document.querySelectorAll(".lang-btn").forEach(btn=>btn.addEventListener("click",()=>{
    currentLang=btn.dataset.lang; applyLanguage();
  }));

  const savedTheme=localStorage.getItem("jarnToTheme")||"dark";
  document.documentElement.dataset.theme=savedTheme;
  document.getElementById("themeBtn").textContent=savedTheme==="dark"?"☀️":"🌙";
  document.getElementById("themeBtn").addEventListener("click",()=>{
    const next=document.documentElement.dataset.theme==="dark"?"light":"dark";
    document.documentElement.dataset.theme=next;
    document.getElementById("themeBtn").textContent=next==="dark"?"☀️":"🌙";
    localStorage.setItem("jarnToTheme",next);
  });

  document.getElementById("menuBtn").addEventListener("click",()=>{
    document.getElementById("navLinks").classList.toggle("open");
  });
  document.querySelectorAll(".nav-links a").forEach(a=>a.addEventListener("click",()=>document.getElementById("navLinks").classList.remove("open")));

  document.querySelectorAll(".filter").forEach(btn=>btn.addEventListener("click",()=>{
    document.querySelectorAll(".filter").forEach(b=>b.classList.remove("active"));
    btn.classList.add("active");
    renderProjects(btn.dataset.filter);
  }));

  document.getElementById("modalClose").addEventListener("click",closeModal);
  document.getElementById("modalBackdrop").addEventListener("click",closeModal);
  document.addEventListener("keydown",e=>{if(e.key==="Escape")closeModal()});

  const observer=new IntersectionObserver(entries=>{
    entries.forEach(e=>{if(e.isIntersecting)e.target.classList.add("visible")});
  },{threshold:.12});
  document.querySelectorAll(".reveal").forEach(el=>observer.observe(el));

  applyLanguage();
});
